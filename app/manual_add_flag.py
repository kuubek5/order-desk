"""«Табличка на дверях»: ручне додавання зараз у польоті.

Проблема, яку це закриває. Ручне додавання робиться у ДВА кроки: спершу рядок
дописується в Google Таблицю (і вона каже, на якому він рядку), і лише потім
робота лягає в базу. Між кроками є щілина в частки секунди. Фоновий синк може
влучити рівно в неї: він читає таблицю, бачить рядок 61, шукає його в базі, не
знаходить — бо крок другий ще не відбувся — і сумлінно СТВОРЮЄ на нього свою
роботу. Тепер робота існує двічі, і коронку фрезерують двічі (аудит 08.09.26).

Синк при цьому не робить нічого поганого: він чинить рівно так, як мусить.
Проблема не в його поведінці, а в тому, що він зазирає в базу в найгіршу мить.

Чому саме так, а не «заборонити базі дві роботи на один рядок». Спробував і
відкотив: при зсуві рядків синк ПЕРЕНУМЕРОВУЄ роботи, і два записи законно
ділять номер посеред перенумерації. Жорстке обмеження вивалювало б помилку
всередині імпорту вкладки — це гірше за дубль (докази в RESILIENCE_PLAN.md).

Що робить цей модуль. Ручне додавання перед першим кроком вішає позначку, а
після другого знімає. Синк перед СТВОРЕННЯМ нових робіт її перевіряє і цього
проходу нових не створює — усе решта (оновлення полів, статуси, архівація) іде
як завжди. Наступний прохід через хвилину бачить роботу вже в базі й спокійно
йде далі.

Три властивості, які роблять це безпечним:

1. **Позначка сама протухає** (`_TTL_SECONDS`). Навіть якщо процес упаде посеред
   додавання і не зніме її, синк не стане мертво — максимум пропустить один
   прохід створення. Це принципова відмінність від замка: замок, який забули
   зняти, тримається вічно.
2. **Синк не зупиняється цілком.** Пропускається рівно та дія, яка дає дубль.
3. **Ціна помилки мінімальна.** Найгірше — нова робота приїде в чергу на
   хвилину пізніше. Оператор щойно бачив, як вона зʼявилась, тож не хвилюється.

Це лікування СИМПТОМУ, і так і задумано. Причина — роз'єднані кроки; правильно
було б звести їх в один потік (варіант «Б» в обговоренні 08.09.26), але це
переміщення коду між шарами. Коли це зроблять, позначку можна просто прибрати.

Стан у памʼяті процесу, не в базі: обидві сторони живуть в одному застосунку,
а запис у базу тут створив би саме ту транзакцію, якої ми уникаємо.
"""

from __future__ import annotations

import logging
import threading
from time import monotonic

logger = logging.getLogger(__name__)

# Скільки позначка живе максимум. Ручне додавання — це один запис у таблицю на
# теплому воркері (~3 с) плюс коміт у базу. 30 с — із запасом на повільну мережу
# і водночас мало, щоб забутий прапорець не зʼїв більше за один прохід синку.
_TTL_SECONDS = 30.0

_lock = threading.Lock()
# Скільки додавань зараз у польоті і коли протухає найпізніше з них.
_in_flight = 0
_expires_at = 0.0


class manual_add_in_flight:
    """Контекст «зараз додаю руками». Використовувати як `with`.

    Лічильник, а не булеве: двоє операторів можуть додавати одночасно, і вихід
    першого не має знімати позначку другого.
    """

    def __enter__(self) -> "manual_add_in_flight":
        global _in_flight, _expires_at
        with _lock:
            _in_flight += 1
            _expires_at = max(_expires_at, monotonic() + _TTL_SECONDS)
        return self

    def __exit__(self, *exc_info) -> bool:
        global _in_flight
        with _lock:
            _in_flight = max(0, _in_flight - 1)
        return False


def manual_add_running() -> bool:
    """Чи є зараз ручне додавання в польоті.

    Протухле НЕ рахується: якщо позначку забули зняти (процес упав посеред
    додавання), вона перестає діяти сама. Синк ніколи не блокується назавжди.
    """
    with _lock:
        if _in_flight <= 0:
            return False
        if monotonic() > _expires_at:
            logger.warning(
                "Позначка ручного додавання протухла (%.0f с) — знімаю сама",
                _TTL_SECONDS,
            )
            return False
        return True


def _reset_for_tests() -> None:
    global _in_flight, _expires_at
    with _lock:
        _in_flight = 0
        _expires_at = 0.0
