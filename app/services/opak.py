"""Опак: одне місце, яке знає, як він виглядає в таблиці й скільки їх.

Опак — покриття цирконієвої коронки рідиною. Він тарифікується окремо, але
власної колонки в Google-таблиці не має: лабораторія вписує його в «Коментар
для CAM-оператора» («2 opaq»), і за зміну рахує очима по цій колонці.

Тут живуть обидва боки конвенції — як портал ПИШЕ опак і як він ЧИТАЄ його
назад числом. Розвести їх по різних файлах означало б рано чи пізно мати дві
різні думки про те, що таке «2 опака», і мовчки недорахувати гроші.

Читання свідомо широке: у таблиці роками пишуть по-різному — «2 opaq»,
«2 опака», «опак», «на швидку, 3 опаки». Пропустити наявний опак дорожче, ніж
підхопити зайве слово: перше — недоплата людині, друге видно очима в паспорті.
"""

from __future__ import annotations

import re

# Слово в будь-якому зі звичних написань: латиною (opaq/opak) і кирилицею.
# Закінчення не перелічуємо — «опак», «опака», «опаків», «опаки», «опаком»
# ловляться основою.
_WORD = r"(?:opa[qk]\w*|опак\w*)"
# Число ПЕРЕД словом — «2 opaq», «1opaq». Це основна форма.
_BEFORE = re.compile(rf"(\d{{1,3}})\s*{_WORD}", re.IGNORECASE)
# Число ПІСЛЯ слова приймаємо тільки через пробіл («опак 2»). Склеєне
# «опаком25» — це не 25 опаків, а початок наступного речення про 25-й зуб:
# у коментарях лабораторії рядки часто злипаються без розділювача.
_AFTER = re.compile(rf"{_WORD}\s+(\d{{1,3}}(?:\s*[,/\-]\s*\d{{1,3}})*)", re.IGNORECASE)
_BARE = re.compile(_WORD, re.IGNORECASE)
_NUMBERS = re.compile(r"\d{1,3}")

# Понад стільки опаків на одну роботу не буває.
_MAX_PLAUSIBLE = 20


def _is_tooth(n: int) -> bool:
    """Чи схоже число на номер зуба за FDI (11-18, 21-28, 31-38, 41-48).

    Живі коментарі рясніють ними: «покрити опаком 14,15», «25 зуб покрити
    опаком». Прочитати такий номер як кількість означає нарахувати за
    роботу, якої не було.
    """
    return 11 <= n <= 48 and 1 <= n % 10 <= 8

def format_opak(raw: str) -> str:
    """Кількість опаків → текст для колонки «Коментар для CAM-оператора».

    Форма «2 opaq» — та, якою пишуть рукою, тож рядок із порталу читається так
    само і не випадає з підрахунку за зміну.

    Нецифровий текст лишаємо як є: оператор іноді дописує уточнення, і зʼїсти
    його гірше, ніж пропустити.
    """
    text = (raw or "").strip()
    if not text:
        return ""
    if not text.isdigit():
        return text
    n = int(text)
    # Нуль опаків — це «опаку немає», а не коментар «0 opaq».
    return f"{n} opaq" if n else ""


def opak_units(comment: str | None) -> int | None:
    """Скільки опаків у коментарі; None — якщо про опак там не йдеться.

    None і 0 — різні відповіді: перше означає «у рядку про опак нічого не
    сказано», друге — «сказано, що нуль». Для звітності це різниця між «не
    заповнили» і «опаку не було».
    """
    text = (comment or "").strip()
    if not text:
        return None
    before = _BEFORE.search(text)
    if before:
        n = int(before.group(1))
        # Кількість пишуть саме так: «2 opaq». Довіряємо, поки число
        # правдоподібне.
        return n if n <= _MAX_PLAUSIBLE else 1

    after = _AFTER.search(text)
    if after:
        numbers = [int(v) for v in _NUMBERS.findall(after.group(1))]
        # Перелік після слова — це зуби, які треба покрити («опаком 14,15»),
        # тобто кількість опаків дорівнює довжині переліку, а не числу в ньому.
        if len(numbers) > 1:
            return len(numbers)
        n = numbers[0]
        if _is_tooth(n) or n > _MAX_PLAUSIBLE:
            return 1
        return n

    # Слово без числа — один опак: саме так це й розуміють у лабораторії
    # («покрити опаком»).
    return 1 if _BARE.search(text) else None
