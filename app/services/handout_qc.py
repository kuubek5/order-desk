"""QC-чеклист на видачі: три звірки перед відміткою «знайдено».

Навіщо. Оператор іде списком клієнтів згори вниз і впізнає коронку ОКОМ —
спільного ключа рядок↔коронка не існує (CLAUDE.md §2). Помилка тут коштує
дорого: чужа робота їде в чужому пакетику, а виявляється це вже в клініці.
Три галочки змушують подивитись саме на те, що найчастіше плутають — форму,
матеріал з кольором і кількість одиниць.

Чому ВИМКНЕНО за замовчуванням. Це зміна процесу, а не виправлення бага:
вона свідомо порушує правило «один клік на дію» (§2) заради страховки. Таке
рішення власника, не наше, тому перемикач стоїть у Налаштуваннях і в новій
базі вимкнений (рішення Роми 06.09.26).

Чому нічого не пишемо в базу. Цінність чеклиста — САМЕ у зупинці погляду, а
не в записі. Зберігати три галочки означало б завести колонки, історію й
звітність під дані, за якими ніхто не приймає рішень; винуватця браку вже
тримає `StatusEvent` (хто відмітив «знайдено»). Тому гейт живе на клієнті, а
сервер лишається тим самим `POST /orders/{id}/mark-found`.
"""

from sqlalchemy.orm import Session

from app.settings_store import get_setting, set_setting

HANDOUT_QC_KEY = "handout_qc_checklist"

# Порядок важливий: він же порядок погляду оператора — спершу форма (найдовше
# дивитись), потім матеріал, потім число.
HANDOUT_QC_ITEMS = [
    "Форма збігається з STL-прев'ю",
    "Матеріал і колір ті самі, що в рядку",
    "Кількість одиниць збігається",
]


def qc_checklist_enabled(db: Session) -> bool:
    """Увімкнений чи ні. Невідоме/порожнє значення = вимкнено: нова база й
    зіпсований ключ шифрування (get_setting деградує в None, §14) не мають
    раптово додавати операторові три кліки на кожну роботу."""
    return (get_setting(db, HANDOUT_QC_KEY) or "") == "1"


def set_qc_checklist(db: Session, enabled: bool) -> None:
    """Не комітить — коміт лишається за роутом, як у решті налаштувань."""
    set_setting(db, HANDOUT_QC_KEY, "1" if enabled else "")
