# Смуга живе в нижній частині екрана RemiCORE (панель керування). Верх кадру не
# скануємо взагалі: там сині елементи інтерфейсу (кнопки, підсвітка рядка
# інструмента), і вони давали б хибні збіги.
#
# Було 0.60 — замало. На п'яти бойових кадрах 03.09.26 (дві роздільності,
# 1280×1024 і 1152×864, різні макети RemiCORE) смуга щоразу стоїть на ~0.90
# висоти кадру. А от вікно G-коду з СУЦІЛЬНОЮ СИНЬОЮ ВИДІЛЕНОЮ ділянкою
# (~215px завширшки, сотні пікселів заввишки) дотягувалось до старої межі
# нижнім краєм — і за довжиною пробігу перемагало справжню заливку. Саме це
# найкращий кандидат на «пише 59, хоча насправді 23». 0.80 лишає смузі
# подвійний запас і виносить вікно G-коду за межі пошуку повністю.
BOTTOM_BAND = 0.80

# Мінімальна ширина заливки. Смуга ~122px, тобто 1% ≈ 1.2px — з порогом 12
# усе нижче 10% не читалось узагалі, і щойно запущена програма показувала
# «не йде» (спіймано наживо 03.09.26). Дрібні сині плями (іконки, текст)
# відсіюються не цим порогом, а вимогою впертись у РАМКУ смуги нижче.
MIN_FILL_WIDTH = 4
# Смуга мусить мати висоту (кілька однакових рядків поспіль), інакше це лінія.
MIN_BAR_HEIGHT = 4
# Правдоподібна геометрія контейнера: смуга прогресу широка й НЕВИСОКА.
MIN_CONTAINER_WIDTH = 40
# Ширина, від якої геометрії можна вірити БЕЗ підпису. Не те саме, що
# MIN_CONTAINER_WIDTH: той пропускає кандидата в детектор, а цей вирішує, чи
# показувати число оператору. Справжні смуги — 120..165px на всіх чотирьох
# верстатах; усе вужче з ЧАСТКОВОЮ заливкою майже напевно чужий елемент.
MIN_TRUSTED_CONTAINER = 100
# Було 60 — удвічі більше за будь-яку справжню смугу. На всіх бойових кадрах
# 03.09.26 смуга ~23px заввишки на обох роздільностях (вона не масштабується
# разом з екраном — це стандартний контрол Windows). Синє виділення у вікні
# G-коду має в смузі пошуку 70+px і колись відсіювалось буквально на межі:
# варто було вікну стати нижче — і воно ставало «смугою». 30 лишає справжній
# смузі запас у третину висоти, а суцільним синім блокам не лишає жодного.
#
# ЗНАНА МЕЖА обох чисел (і цього, і BOTTOM_BAND): вони зміряні на двох
# роздільностях, які є в цеху зараз. Смуга — стандартний контрол Windows і з
# екраном не масштабується, тому 30 має триматись і далі; але якщо колись
# зʼявиться верстат із сильно іншим DPI і його плитка мовчатиме («програма не
# йде» при живих кадрах) — перше, що треба зробити, це зняти з нього кадр і
# перевіряти саме ці дві межі, а не шукати баг деінде.
MAX_BAR_HEIGHT = 30
# Найширша «дірка» в порожній частині, яку вважаємо підписом поверх смуги, а не
# її кінцем. Літера підпису — кілька пікселів; фон панелі тягнеться сотнями.
MAX_LABEL_GAP = 14
# Яка частка рядків смуги має бути темною, щоб вважати колонку РАМКОЮ, а не
# літерою підпису. Рамка йде на всю висоту, літера — на частину.
BORDER_DARK_SHARE = 0.7
# Скільки пікселів між заливкою й рамкою вважаємо згладженим краєм, а не
# залишком. На смузі ~128px це < 2%, тобто нижче її власної роздільності.
EDGE_SLACK = 2
# Скільки найдовших пробігів перевіряти на «форму смуги». Найдовший у кадрі —
# панель задач Windows (заввишки 2px), тож одним кандидатом не обійтись.
MAX_BAR_CANDIDATES = 40
# Крок пошуку смуги по рядках. Безпечний, доки він менший за MIN_BAR_HEIGHT.
SEED_ROW_STEP = 2


# `_cache_only_success` живе в app/furnace_ocr.py — там, куди вже йде
# залежність цього модуля (див. імпорт вище). Одна реалізація на два екрани.


def _is_blue(px: tuple[int, int, int]) -> bool:
    """Заливка смуги. Виміряно на реальному кадрі 02.09.26: чиста темна синь
    `(0, 0, 128)`, тобто r == g і синій різко переважає. Поріг узятий із запасом
    на згладжування країв і на світліші пікселі тексту поверх смуги."""
    r, g, b = px[0], px[1], px[2]
    # `g <= 140` відсікає СВІТЛІ сині елементи інтерфейсу: на портретному
    # RemiCORE (.64) є синя іконка-пігулка з градієнтом (~100,170,230), і без
    # цієї умови вона перемагала справжню смугу за довжиною пробігу — 8%
    # читалось як 47% (04.09.26). Справжня заливка — рівна темна навісь
    # (0,0,128), у неї g=0.
    return b >= 90 and b - r >= 40 and b - g >= 40 and g <= 140


def _is_unfilled(px: tuple[int, int, int]) -> bool:
    """Порожня частина смуги — ЧИСТО БІЛА (255), а фон панелі RemiCORE сірий
    (240). Тому поріг саме 250, а не «світле взагалі»: з м'яким порогом
    контейнер розповзався по всій сірій панелі й відсоток виходив мізерним."""
    return px[0] >= 250 and px[1] >= 250 and px[2] >= 250


@dataclass(frozen=True)
class ProgressBar:
    percent: int
    fill_width: int
    container_width: int
    box: tuple[int, int, int, int]  # left, top, right, bottom заливки — для доказу


def _is_dark(px: tuple[int, int, int]) -> bool:
    """Піксель рамки: помітно темніший за будь-яке тло панелі."""
    return max(px[0], px[1], px[2]) <= 180


def _is_fill_column(px, x: int, band: list[int]) -> bool:
    """Чи колонка `x` — ЗАЛИВКА смуги (а не літера підпису на порожній частині).

    Заливка синя на ВСЮ висоту смуги, тож синя і вгорі, і внизу band. Літера
    підпису стоїть у середині: над нею й під нею — тло. Ця відмінність і
    рятує від того, щоб синій підпис на порожній частині зарахувався в
    заливку (див. коментар у скані).
    """
    if not band:
        return False
    return _is_blue(px[x, band[0]]) and _is_blue(px[x, band[-1]])


def _is_solid_fill(px, x0: int, x1: int, band: list[int]) -> bool:
    """Чи пробіг `x0..x1` — СУЦІЛЬНА заливка, а не синій текст.

    Головна ознака смуги: заливка синя на ВСЮ висоту, тобто і в найверхньому,
    і в найнижчому рядку band. Синій напис («B 0.00» у полі координати,
    «100%» біля повзунка) дає довгий пробіг у тому рядку, де його перетнула
    горизонтальна частина літери, але вгорі й унизу там тло.

    Саме на цьому детектор ловився, коли справжня заливка була ще завузькою,
    щоб бути зачіпкою: на кадрі .60 при 1% він віддавав то 23%, то 26%, то 48%
    — три різні чужі елементи, і всі три виглядали правдоподібно (04.09.26).

    Кілька відсотків неспівпадіння лишаємо на згладжені краї пробігу.
    """
    if not band or x1 < x0:
        return False
    solid = sum(1 for x in range(x0, x1 + 1) if _is_fill_column(px, x, band))
    return solid >= (x1 - x0 + 1) * 0.9


def _is_edge_column(px, x: int, band: list[int]) -> bool:
    """Кінець КОНТЕЙНЕРА смуги: колонка, де на всю висоту немає ні заливки,
    ні білого треку.

    Узагальнення `_is_border_column`, яка вимагала ТЕМНОЇ рамки (max<=180). На
    портретному RemiCORE (.64) рамка контейнера світло-сіра (227), тож скан не
    спинявся й тікав до краю кадру — смуга не читалась узагалі (04.09.26).
    Літера підпису такою колонкою не буде: над нею й під нею лишається білий
    трек, тобто не «на всю висоту».
    """
    if len(band) < 3:
        return False
    return all(
        not _is_blue(px[x, y]) and not _is_unfilled(px[x, y]) for y in band
    )


def _is_border_column(px, x: int, band: list[int], height: int = 10**9) -> bool:
    """Чи колонка `x` — вертикальна РАМКА смуги (а не літера підпису).

    Рамка йде на всю висоту смуги, літера — лише на частину. Тому дивимось не
    на один піксель, а на частку темних рядків у смузі: рамка дає майже всі,
    підпис — меншість.
    """
    if len(band) < 3:
        return False
    # Беремо ще по рядку ЗА межами заливки: справжня рамка — це прямокутник,
    # тож вона темна і там; підпис усередині смуги — ні. Без цього високий
    # підпис («23 %») на короткій смузі проходив за рамку, скан спинявся на
    # ньому й контейнер виходив коротким — 23% читались як 59%
    # (спіймано наживо 03.09.26).
    rows = [y for y in (band[0] - 1, *band, band[-1] + 1) if 0 <= y < height]
    dark = sum(1 for y in rows if _is_dark(px[x, y]))
    return dark >= len(rows) * BORDER_DARK_SHARE


def find_progress_bar(image: Image.Image, masks: "_FrameMasks | None" = None) -> Optional[ProgressBar]:
    """Знайти смугу прогресу й порахувати відсоток. None — якщо не впевнені.

    Позиція смуги НЕ зашита: інші верстати можуть мати інший макет і
    роздільність, тому вона щоразу шукається за формою й кольором.
    """
    import numpy as np

    m = masks or _FrameMasks(image)
    rgb = m.image
    width, height = m.width, m.height
    if width < 80 or height < 60:
        return None

    top = int(height * BOTTOM_BAND)
    px = rgb.load()
    # Ті самі три предикати (`_is_blue` / `_is_unfilled` / `_is_dark`), лише
    # застосовані до всього кадру одразу. Попіксельний обхід нижньої смуги
    # коштував 25-43 мс на кадр, і платив за нього не лише читач: процес
    # опитує сім верстатів кожні 5 с, тож ці мілісекунди — постійне
    # навантаження, за яким у черзі стоять і видача, і синк (заміри 09.09.26).
    # Відповіді НЕ міняються — звірено на 490 бойових кадрах.
    blue_mask = m.blue
    white_mask = m.white
    dark_mask = m.dark

    # 1) Найдовший СУЦІЛЬНИЙ пробіг синього в нижній частині кадру — це і є
    #    заливка смуги. Саме пробіг, а не «розмах синього в рядку»: розмах
    #    захоплював ще й синій напис «100%» ЛІВОРУЧ від смуги та розкидані сині
    #    цифри таблиці інструментів, і детектор міряв зовсім не ту область
    #    (бойовий випадок 03.09.26 — «смуга» шириною 741px через пів екрана).
    # Шукаємо ЧЕРЕЗ РЯДОК: смуга щонайменше MIN_BAR_HEIGHT (4px) заввишки, тож
    # крок 2 не може її проґавити, а розбір кадру коштує вдвічі менше — це
    # дозволяє опитувати верстати частіше без зростання навантаження.
    runs: list[tuple[int, int, int, int]] = []  # (довжина, y, x0, x1)
    for y in range(top, height, SEED_ROW_STEP):
        idx = np.flatnonzero(blue_mask[y])
        if idx.size == 0:
            continue
        # Пробіг тут СУЦІЛЬНИЙ — жодного допуску на дірку, на відміну від
        # плаского UI: розрив означає новий пробіг.
        breaks = np.flatnonzero(np.diff(idx) > 1)
        starts = np.concatenate(([0], breaks + 1))
        ends = np.concatenate((breaks, [idx.size - 1]))
        for i, j in zip(starts, ends):
            x_start = int(idx[i])
            x_end = int(idx[j])
            if x_end - x_start + 1 >= MIN_FILL_WIDTH:
                runs.append((x_end - x_start + 1, y, x_start, x_end))
    if not runs:
        return None

    # 2) Кандидати — за довжиною, але беремо ПЕРШИЙ, що має форму смуги
    #    (потрібна висота). Найдовший пробіг у кадрі — панель задач Windows
    #    заввишки 2px; відкидати лише її й здаватись не можна, інакше справжня
    #    смуга нижче так і не розглядається (бойовий випадок 03.09.26).
    def band_of(left: int, y_seed: int) -> list[int]:
        column = blue_mask[:, left]
        above = np.flatnonzero(~column[:y_seed])
        y_top = int(above[-1]) + 1 if above.size else 0
        below = np.flatnonzero(~column[y_seed + 1:])
        y_bot = y_seed + int(below[0]) if below.size else height - 1
        return list(range(y_top, y_bot + 1))

    band: list[int] = []
    left = fill_right = 0
    # Відкинуті області, щоб не переглядати ту саму двічі. БЕЗ цього великий
    # суцільний синій блок (виділений блок рядків у вікні G-коду — ~215px
    # завширшки, сотні пікселів заввишки) віддає по ОДНОМУ пробігу на кожен
    # сканований рядок, тобто десятки однакових кандидатів, і всі вони довші
    # за справжню заливку. Ліміт MAX_BAR_CANDIDATES вичерпувався на самому
    # лише блоці — справжня смуга нижче не розглядалась ЖОДНОГО разу
    # (бойові кадри 03.09.26). Тепер ліміт рахує РІЗНІ області, а не рядки.
    rejected: list[tuple[int, int, int, int]] = []

    def already_rejected(x: int, y: int) -> bool:
        return any(x0 <= x <= x1 and y0 <= y <= y1 for x0, x1, y0, y1 in rejected)

    tried = 0
    for _, y_seed, x0, x1 in sorted(runs, key=lambda r: -r[0]):
        if already_rejected(x0, y_seed):
            continue
        if tried >= MAX_BAR_CANDIDATES:
            break
        tried += 1
        candidate = band_of(x0, y_seed)
        # Та сама умова, що в `_is_solid_fill`: колонка вважається заливкою,
        # коли синя і вгорі, і внизу смуги, і таких мусить бути ≥90%.
        solid = False
        if candidate:
            cols = blue_mask[candidate[0], x0:x1 + 1] & blue_mask[candidate[-1], x0:x1 + 1]
            solid = int(cols.sum()) >= (x1 - x0 + 1) * 0.9
        if MIN_BAR_HEIGHT <= len(candidate) <= MAX_BAR_HEIGHT and solid:
            band, left, fill_right = candidate, x0, x1
            break
        rejected.append((x0, x1, candidate[0], candidate[-1]) if candidate
                        else (x0, x1, y_seed, y_seed))
    if not band:
        return None

    # 3) ОДИН прохід зліва направо від початку смуги. Підпис («100 %») може
    #    стояти і на заливці, і на порожній частині — його літери просто
    #    пропускаємо. Спиняємось на РАМЦІ смуги: вона темна на всю висоту,
    #    а літера — лише на частину (без цього скан їхав далі по білому тлу
    #    панелі й роздував контейнер: повна смуга читалась як 85%).
    y_mid = band[len(band) // 2]
    last_blue = fill_right
    last_white = fill_right
    gap = 0
    hit_border = False
    # Ті самі чотири предикати, порахований наперед на ВЕСЬ рядок. Раніше цей
    # прохід читав по ~40 пікселів на коженx (рамка дивиться всю висоту смуги,
    # край — теж), тобто десятки тисяч звернень на кадр. Логіка проходу
    # лишається послідовною: він має спинятись на рамці, а не «зібрати все».
    _band = np.array(band, dtype=np.intp)
    _rows = np.array([y for y in (band[0] - 1, *band, band[-1] + 1)
                      if 0 <= y < height], dtype=np.intp)
    if len(band) >= 3:
        _is_border = (dark_mask[_rows].sum(axis=0) >= len(_rows) * BORDER_DARK_SHARE).tolist()
        _is_edge = (~(blue_mask[_band] | white_mask[_band]).any(axis=0)).tolist()
    else:
        _is_border = [False] * width
        _is_edge = [False] * width
    _fill_col = (blue_mask[band[0]] & blue_mask[band[-1]]).tolist()
    _blue_mid = blue_mask[y_mid].tolist()
    _white_mid = white_mask[y_mid].tolist()
    for x in range(fill_right + 1, width):
        if _is_border[x] or _is_edge[x]:
            hit_border = True
            break
        if _fill_col[x]:
            # Заливка — це колонка, синя ВГОРІ І ВНИЗУ смуги. Літери підпису
            # займають лише середину, тож так вони не подовжують заливку.
            last_blue = x
            gap = 0
        elif _white_mid[x]:
            last_white = x
            gap = 0
        elif _blue_mid[x]:
            # Синє лише в середині — це ПІДПИС на порожній частині. RemiCORE
            # малює його тим самим темно-синім, що й заливку, і на низькому
            # відсотку скан по середньому рядку хапав його як заливку: «18%»
            # читалось як 57% (бойовий кадр .76, 04.09.26). Рахуємо як літеру:
            # заливку не подовжує, скан не спиняє.
            gap = 0
        else:
            gap += 1
            if gap > MAX_LABEL_GAP:
                break

    fill = last_blue - left + 1
    # Щілина в 1-2 пікселі між заливкою й рамкою — згладжування краю, а не
    # залишок: на смузі ~128px піксель ≈ 0.8%, тобто нижче її роздільності.
    right_edge = max(last_blue, last_white)
    if right_edge - last_blue <= EDGE_SLACK:
        right_edge = last_blue
    container = right_edge - left + 1
    if container < MIN_CONTAINER_WIDTH:
        return None
    # Справжня смуга ЗАВЖДИ закінчується рамкою. Саме ця вимога (а не грубий
    # поріг ширини заливки) відсіює сині іконки й текст — і водночас дозволяє
    # читати зовсім малий відсоток на щойно запущеній програмі.
    if not hit_border:
        return None

    percent = round(fill * 100 / container)
    if percent < 0 or percent > 100:
        return None
    return ProgressBar(
        percent=percent, fill_width=fill, container_width=container,
        box=(left, band[0], last_white + 1, band[-1] + 1),
    )


# ── Дуже низький відсоток: зачіпка за БІЛИЙ трек, а не за заливку ───────────
# При 2% заливка ~2px — вона не проходить ані MIN_FILL_WIDTH, ані відбір
# кандидатів за довжиною (дрібніша за будь-який синій напис на екрані). А от
# білий трек довгий ЗАВЖДИ, тому на малих відсотках зачіпляємось за нього й
# міряємо заливку ліворуч. Бойовий випадок .85 на 2% (04.09.26): віджет не
# показував нічого, хоч програма щойно стартувала — саме той момент, коли
# оператор і хоче побачити, що вона пішла.
LOW_MIN_TRACK_WIDTH = 40
# Власний, СУВОРІШИЙ мінімум контейнера для цього шляху. Справжня смуга
# RemiCORE — 115..166px; дрібні білі поля інтерфейсу (49px на пласких
# екранах нового покоління) давали хибні «0%». Хибне гірше за жодне.
LOW_MIN_CONTAINER = 80


def _find_bar_by_track(image: Image.Image, masks: "_FrameMasks | None" = None) -> Optional[ProgressBar]:
    import numpy as np

    m = masks or _FrameMasks(image)
    source = m.image
    px = source.load()
    width, height = m.width, m.height
    white_mask = m.white
    start_y = int(height * BOTTOM_BAND)

    # Кандидатів БАГАТО, і найдовший — не наш: на портретному RemiCORE
    # найдовший білий пробіг у нижній смузі це панель списку (538px, висота 1),
    # а справжній трек ~150px. Тому перебираємо за довжиною, доки якийсь не
    # пройде перевірки форми й рамок — так само, як головний детектор.
    runs: list[tuple[int, int, int, int]] = []
    for y in range(start_y, height, SEED_ROW_STEP):
        idx = np.flatnonzero(white_mask[y])
        if idx.size == 0:
            continue
        breaks = np.flatnonzero(np.diff(idx) > 1)
        starts = np.concatenate(([0], breaks + 1))
        ends = np.concatenate((breaks, [idx.size - 1]))
        for i, j in zip(starts, ends):
            x_start = int(idx[i])
            x_end = int(idx[j])
            if x_end - x_start + 1 >= LOW_MIN_TRACK_WIDTH:
                runs.append((x_end - x_start + 1, x_start, x_end, y))
    runs.sort(key=lambda r: -r[0])

    for _, w0, w1, y in runs[:MAX_BAR_CANDIDATES]:
        # Пробна колонка — біля ПРАВОГО краю треку, а не в середині: підпис
        # стоїть по центру, і колонка крізь літеру дає обрізану висоту смуги
        # (9 замість 24), через що підпис потім не читається взагалі.
        xm = max(w0, w1 - 2)
        column = white_mask[:, xm]
        above = np.flatnonzero(~column[:y])
        top = int(above[-1]) + 1 if above.size else 0
        below = np.flatnonzero(~column[y + 1:])
        bottom = y + int(below[0]) if below.size else height - 1
        band = list(range(top, bottom + 1))
        if not (MIN_BAR_HEIGHT <= len(band) <= MAX_BAR_HEIGHT):
            continue

        # Ліворуч від треку — заливка (нульової ширини на 0%).
        fill = 0
        x = w0 - 1
        while x > 0 and _is_fill_column(px, x, band):
            fill += 1
            x -= 1
        left = w0 - fill
        if left - 1 <= 0 or w1 + 1 >= width:
            continue
        left_ok = (_is_border_column(px, left - 1, band, height)
                   or _is_edge_column(px, left - 1, band))
        right_ok = (_is_border_column(px, w1 + 1, band, height)
                    or _is_edge_column(px, w1 + 1, band))
        if not (left_ok and right_ok):
            continue

        container = w1 - left + 1
        if container < LOW_MIN_CONTAINER:
            continue
        percent = round(fill * 100 / container)
        if percent < 0 or percent > 100:
            continue
        return ProgressBar(
            percent=percent, fill_width=fill, container_width=container,
            box=(left, band[0], w1 + 1, band[-1] + 1),
        )
    return None


def read_progress_percent(image: Image.Image) -> Optional[int]:
    """Відсоток виконання програми або None.

    Два незалежні сигнали, і головніший — ПІДПИС: «43%» усередині смуги це те,
    що верстат сам про себе пише, а геометрія (частка заливки) лише оцінка.
    Геометрія промахується на згладженому краї заливки й на невдало знайдених
    межах контейнера — саме на цьому вона ламалась сім разів; підпис від цього
    не залежить узагалі.

    Підпис читається шаблонами піксель-у-піксель, тож він або точний, або його
    немає: доки еталони не донавчені (`scripts/machine_glyphs.py learn`),
    повертається геометрія — рівно та поведінка, що була дотепер. Тобто новий
    сигнал може лише виправити число, але не зіпсувати.
    """
    # Маски кадру рахуються ОДИН раз на всі три детектори: вони йдуть підряд по
    # одному й тому ж кадру, і кожен будував собі площини заново.
    masks = _FrameMasks(image)
    bar = find_progress_bar(image, masks)
    if bar is None:
        # ПОРЯДОК ВАЖЛИВИЙ. Спершу нове покоління (окремий, добре захищений
        # детектор), і лише потім зачіпка за білий трек: інакше fallback
        # перехоплював плаский UI й віддавав 0% замість справжніх 0..30
        # (спіймано на бойових кадрах .81, 04.09.26).
        newgen = find_newgen_progress(image, masks)
        if newgen is not None:
            return newgen.percent
        # Дуже низький відсоток на RemiCORE: заливка завузька, щоб бути
        # зачіпкою. Пробуємо зачепитись за білий трек (він довгий завжди).
        # Цей шлях довіряємо ЛИШЕ з підтвердженням підпису: зачіпка за біле
        # знаходить і чужі світлі панелі інтерфейсу (на .85 така дала «0%»),
        # а справжня смуга ЗАВЖДИ має написане число. Немає числа — мовчимо.
        low = _find_bar_by_track(image, masks)
        if low is None:
            return None
        low_caption = read_caption_percent(image, low)
        return low_caption
    if bar is None:
        return None
    caption = read_caption_percent(image, bar)
    if caption is not None and caption != bar.percent:
        # Розбіжність — не привід мовчати (число все одно є), але привід
        # лишити слід: якщо вона систематична, значить межі смуги знаходяться
        # неправильно, і це видно лише тут.
        #
        # РОЗМІР розбіжності вирішує, чи це слід узагалі. Смуга в цеху —
        # 120..165 px, тож один піксель згладженого краю заливки коштує
        # менше відсотка: розбіжність на 1 в. п. — це округлення оцінки, про
        # яке докстрінг вище й попереджає, і воно писалось у лог кожні 6 с на
        # кожен верстат (08.09.26: половина цехового лога — саме ці рядки).
        # Мовчимо про неї на рівні INFO; справжня біда — коли межі знайдено
        # не там, і тоді розбіжність не в одиницях.
        if abs(caption - bar.percent) <= 1:
            logger.debug(
                "Верстат: підпис %d%% проти геометрії %d%% — округлення",
                caption, bar.percent,
            )
        else:
            logger.info(
                "Верстат: підпис %d%% розійшовся з геометрією %d%% — беремо підпис",
                caption, bar.percent,
            )
    if caption is not None:
        return caption
    # Геометрія БЕЗ підпису довіряється не завжди. Небезпечне поєднання —
    # вузький контейнер із ЧАСТКОВОЮ заливкою: у смузі на 40px один піксель
    # коштує 2.5%, тож будь-який сторонній синій елемент інтерфейсу дає
    # правдоподібне середнє число з повітря. Справжні смуги в цеху — 120..165px
    # на всіх чотирьох верстатах (зміряно на 285 бойових кадрах).
    #
    # Раніше тут стояв виняток для 100%: мовляв, повна вузька смуга однозначна.
    # Виняток був помилкою і тримався на єдиному «прикладі» — кадрі .64 з
    # контейнером 53px. Рев'ю 04.09.26 змусило подивитись на нього оком: це
    # виявився шматок ШПАЛЕР Windows, а не смуга. Тобто виняток захищав
    # неіснуючий випадок і водночас пропускав найдорожче хибне число — 100%,
    # після якого оператор іде знімати недофрезеровану роботу.
    #
    # Тепер правило без винятків: вузький контейнер приймаємо лише з
    # підтвердженням підпису.
    if bar.container_width < MIN_TRUSTED_CONTAINER:
        logger.info(
            "Верстат: контейнер %dpx завузький для %d%% без підпису — мовчимо",
            bar.container_width, bar.percent,
        )
        return None
    return bar.percent


# ── Ім'я .iso-програми із заголовка вікна RemiCORE ──────────────────────────
# Реальний заголовок (кадр 02.09.26):
#   `Remote - zr18_18-Monolith-A3-x62_2026-09-02_23-04-33.iso`
# У ньому дата+час — той самий ідентифікатор, що оператор вписує як Sum3D ID
# (хвіст `HH-MM-SS`). Це і є ключ, який зв'язує верстат із рядком черги.
#
# Читаємо з ТЕКСТУ заголовка (агент бере його з Windows), а не з картинки:
# здогадки тут неприпустимі — або точне ім'я, або нічого.
# Ім'я файлу — без пробілів і роздільників шляху, тож префікс вікна
# («Remote - ») у нього не залипає.
_ISO_RE = re.compile(
    r"(?P<program>[^\s\\/]*(?P<date>\d{4}-\d{2}-\d{2})[_-](?P<time>\d{2}-\d{2}-\d{2})[^\s\\/]*\.iso)",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class MillingProgram:
    iso_name: str      # повне ім'я файлу програми
    sum3d_id: str      # хвіст HH-MM-SS — ключ до рядка черги
    date: str          # YYYY-MM-DD з імені


def parse_iso_title(title: str) -> Optional[MillingProgram]:
    """Заголовок вікна → програма, що фрезерується. None, якщо це не воно."""
    if not title:
        return None
    m = _ISO_RE.search(title)
    if not m:
        return None
    return MillingProgram(
        iso_name=m.group("program").strip(),
        sum3d_id=m.group("time"),
        date=m.group("date"),
    )


def pick_milling_program(titles) -> Optional[MillingProgram]:
    """Обрати програму серед УСІХ заголовків вікон верстата.

    Агент віддає всі видимі вікна, бо вгадувати «те саме» вікно на його боці —
    зайва здогадка. Тут беремо перший заголовок, що виглядає як `.iso`-програма;
    якщо таких кілька (відкрито два вікна RemiCORE), беремо перший — але лише
    коли всі вони кажуть про ОДНУ програму, інакше нічого: два різні кандидати
    означають, що ми не знаємо, який фрезерується (принцип «краще нічого»).
    """
    found = [p for p in (parse_iso_title(t) for t in (titles or [])) if p]
    if not found:
        return None
    first = found[0]
    if any(p.sum3d_id != first.sum3d_id or p.date != first.date for p in found):
        return None
    return first


# ── Другий сигнал: ПІДПИС усередині смуги ──────────────────────────────────
# Геометрія смуги — оцінка (частка заливки), а підпис «43%» — це те, що
# верстат САМ про себе пише. Тому підпис, прочитаний точно, головніший за
# геометрію: він не залежить ні від згладженого краю заливки, ні від того, чи
# правильно ми знайшли межі контейнера. Але прочитаний саме ТОЧНО — правило
# модуля незмінне: хибне число гірше за жодне, тож при найменшому сумніві
# лишається геометрія, як і раніше.
#
# Складність рівно одна, і вона видна на будь-якому кадрі з частковим
# прогресом: підпис стоїть по центру КОНТЕЙНЕРА, тому на межі заливки він
# розрізаний навпіл — ліва половина біла на темно-синьому, права темна на
# світлому тлі. Тому крамп нормалізується у чорно-білу маску ДО розрізання на
# символи, і вже маска віддається спільним помічникам печей.

MACHINE_GLYPHS_PATH = "app/data/machine_glyphs.json"

# Підпис на заливці: майже чистий білий (виміряно на кадрі — (255, 255, 255)).
_CAPTION_LIGHT_MIN = 200
# Підпис на порожній частині: темний текст на світлому тлі панелі (240,240,240).
_CAPTION_DARK_MAX = 120
# Скільки пікселів відступити від рамки всередину. Рамка темна на всю висоту
# і без відступу потрапила б у маску як «символ».
_CAPTION_INSET = 3


@_cache_only_success
def load_machine_glyphs() -> dict[int, dict[str, list[list[str]]]]:
    """Еталони цифр підпису: висота → символ → варіанти бітмап.

    Порожньо — нормальний стан до першого калібрування: підпис просто не
    читається, а відсоток і далі береться з геометрії. Гучно не скаржимось,
    бо це не поломка, а «ще не навчено» (на відміну від печей, де без еталонів
    зникають УСІ числа).
    """
    path = Path(resource_path(MACHINE_GLYPHS_PATH))
    if not path.exists():
        return {}
    # Читання ЗАХИЩЕНЕ: файл пишеться скриптом навчання звичайним write_text
    # (без tmp+replace), тож конкурентне читання може впіймати обрізаний JSON.
    # Виняток звідси не просто гасив би відсоток — він валив би ВЕСЬ екран
    # «Верстати» 500-ю, бо ця функція викликається ще й із calibration_status()
    # у контексті сторінки, поза межами будь-якого try (рев'ю 04.09.26).
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        logger.warning("machine_glyphs.json не прочитано — підпис поки не читаємо")
        return {}
    if not isinstance(raw, dict):
        return {}
    return {int(h): chars for h, chars in (raw.get("fonts") or {}).items()}


def missing_caption_digits() -> set[str]:
    """Які цифри 0-9 ще НЕ вивчено для підпису смуги.

    На цьому тримається авто-збір калібрувальних кадрів: доки набір неповний,
    програма сама відкладає кадри з новими відсотками; щойно всі десять цифр
    є — збір зупиняється. Так робочий ПК (де лише встановлена програма, без
    Python) сам готує матеріал для навчання, а оператор його лише скачує.
    """
    seen: set[str] = set()
    for chars in load_machine_glyphs().values():
        seen.update(c for c in chars if c.isdigit())
    return set("0123456789") - seen


def caption_mask(image: Image.Image, bar: "ProgressBar") -> Optional[Image.Image]:
    """Чорно-біла маска підпису всередині смуги (чорне — символ).

    Нормалізація потрібна саме тому, що підпис двоколірний: на заливці він
    світлий, поза нею — темний. Після маски обидві половини одного й того ж
    «43%» виглядають однаково, і далі працюють ті самі помічники, що на печах.
    """
    left, top, _right, bottom = bar.box
    container_right = left + bar.container_width
    # Межа світле/темне — це край ЗАЛИВКИ, а не контейнера. bar.box[2] — правий
    # край КОНТЕЙНЕРА (== left + container_width), тож поділ по ньому означав
    # «уся смуга залита» і порожню білу частину маска брала за текст (чорний
    # блок справа). На 100% заливка == контейнер, і це збігалось — тому баг не
    # спливав до калібрування реальними частковими кадрами (04.09.26).
    fill_edge = left + bar.fill_width
    x0, y0 = left + _CAPTION_INSET, top + _CAPTION_INSET
    x1, y1 = container_right - _CAPTION_INSET, bottom - _CAPTION_INSET
    if x1 - x0 < 8 or y1 - y0 < 5:
        return None

    source = image.convert("RGB")
    px = source.load()
    mask = Image.new("RGB", (x1 - x0, y1 - y0), (255, 255, 255))
    mpx = mask.load()
    for y in range(y0, y1):
        for x in range(x0, x1):
            r, g, b = px[x, y][:3]
            if x < fill_edge:
                # На заливці символ світлий. Саму синь відсікає нижня межа.
                is_ink = min(r, g, b) >= _CAPTION_LIGHT_MIN
            else:
                # Поза заливкою символ темний на світлому тлі панелі.
                # `min`, а НЕ `max`: поза заливкою RemiCORE малює підпис тим
                # самим темно-синім, що й заливка (0,0,128). Його max = 128,
                # тобто поріг по max його пропускав, і на низькому відсотку
                # підпис не читався взагалі (бойовий кадр .76 «18%»,
                # 04.09.26). `min` ловить і синє (min=0), і темно-сіре, але
                # відкидає світле тло смуги (min≈240).
                is_ink = min(r, g, b) <= _CAPTION_DARK_MAX
            if is_ink:
                mpx[x - x0, y - y0] = (0, 0, 0)
    return mask


def _caption_ink(color) -> bool:
    return color[0] < 128


def read_caption_percent(image: Image.Image, bar: "ProgressBar") -> Optional[int]:
    """Відсоток, ПРОЧИТАНИЙ з підпису смуги. None — якщо не впевнені.

    None повертається щедро й свідомо: немає еталонів, символ не збігся
    піксель-у-піксель, прочиталось не число, число поза 0..100 — усе це
    привід мовчати, а не вгадувати.
    """
    glyphs = load_machine_glyphs()
    if not glyphs:
        return None
    mask = caption_mask(image, bar)
    if mask is None:
        return None

    boxes = _segments(mask, _caption_ink)
    if not boxes or len(boxes) > 6:
        return None

    # Цифри йдуть ЗЛІВА; усе після них — знак «%» (у якому завгодно числі
    # сегментів і якої завгодно висоти) і ігнорується. Причина: «%» рендериться
    # варіативно — то один сегмент висотою 13, то два по 10 (розсипається на
    # два кружечки + риску), залежно від шрифту й краю заливки. Вимагати точний
    # збіг «%» означало відкидати цілий вірний підпис через декоративний знак
    # (бойовий випадок 04.09.26: «57%» не читалось, бо «%» був висотою 13).
    # Захист «хибне гірше за жодне» лишається: щойно почалась зона «%», ЖОДНА
    # наступна цифра не дозволена — зламана цифра посеред числа дасть None, а
    # не коротше число.
    digits = ""
    seen_pct = False
    for box in boxes:
        bitmap = _bitmap(mask, box, _caption_ink)
        char = _match_digit(bitmap, glyphs)
        if char is not None and char.isdigit():
            if seen_pct:
                return None  # цифра після «%» — підпис розібрано неправильно
            digits += char
        else:
            # Матчений «%», або несходимий сегмент — це початок зони «%».
            # Далі мають бути тільки такі; поява цифри вище дасть None.
            seen_pct = True

    if not digits or len(digits) > 3:
        return None
    value = int(digits)
    return value if 0 <= value <= 100 else None


# ── Нове покоління (CORiTEC 250i PRO+ / плаский UI) ─────────────────────────
# Інший софт, інший екран: рядок «PROGRESS [смуга] NN%» унизу картки GENERAL.
# Читається ПРОСТІШЕ за RemiCORE, і саме тому окремою функцією:
#   • смуга — рівний прямокутник БЕЗ напису всередині (число стоїть праворуч
#     ЗОВНІ), тож немає плутанини «літери підпису = заливка», через яку
#     RemiCORE вимагав стільки запобіжників;
#   • заливка й порожній трек — два різні рівні сірого/синього, обидва помітно
#     відрізняються від фону картки.
# Виміряно на бойових кадрах .81 (1920×1200, 04.09.26): заливка (0,104,178),
# трек (89,89,89), фон (66,66,66); смуга ~561px завширшки, ~20px заввишки.
# Координати НЕ зашиті — шукаємо за кольором і формою, як і на RemiCORE.

# Заливка: виразно синій, синього помітно більше за червоний.
def _ng_is_fill(px) -> bool:
    r, g, b = px[0], px[1], px[2]
    return b >= 140 and b - r >= 80 and b > g


# Порожній трек: нейтральний сірий, СВІТЛІШИЙ за фон картки (66) і темніший
# за текст. Вузький діапазон навмисно — інакше трек «розповзається» по фону.
def _ng_is_track(px) -> bool:
    r, g, b = px[0], px[1], px[2]
    return abs(r - g) <= 10 and abs(g - b) <= 10 and 76 <= r <= 110


def _ng_is_bg(px) -> bool:
    """Фон картки плаского UI — темний нейтральний сірий (виміряно 66,66,66)."""
    r, g, b = px[0], px[1], px[2]
    return max(r, g, b) <= 80 and abs(r - g) <= 12 and abs(g - b) <= 12


# Смуга нового покоління: широка й невисока. Кнопки PAUSE/STOP теж сині, але
# у них висота в рази більша — саме нею вони й відсіюються.
NG_MIN_WIDTH = 200
NG_MIN_HEIGHT = 6
# 60, а не 40: навколо смуги є проміжні відтінки сірого, і вимір товщини
# захоплює їх (на бойовому кадрі вийшло 46 замість візуальних ~20). Кнопки
# PAUSE/STOP заввишки ~180px, тож 60 їх однаково відсікає.
NG_MAX_HEIGHT = 60
NG_ROW_STEP = 3
# Скільки згладжених пікселів терпимо ВСЕРЕДИНІ смуги і за її краєм. На 150i
# PRO (M3.1) між заливкою й треком стоїть перехідний (44,97,134) — не заливка й
# не трек, — а зліва від смуги такий самий перехід до фону. Без цього допуску
# детектор бачив лише трекову половину смуги й мовчав (04.09.26).
NG_EDGE_SLACK = 3


class _FrameMasks:
    """Маски кадру, пораховані ОДИН раз і роздані всім читачам.

    Три детектори підряд (`find_progress_bar` → `find_newgen_progress` →
    `_find_bar_by_track`) працюють по одному й тому ж кадру, і кожен будував
    собі площини заново — на 1920×1200 це втричі по кілька мілісекунд плюс
    втричі памʼять. Тут вони рахуються лінькувато (тільки те, що справді
    попросили) і живуть рівно стільки, скільки триває розбір кадру.
    """

    __slots__ = ("image", "width", "height", "_planes", "_cache")

    def __init__(self, image: Image.Image):
        self.image = image.convert("RGB")
        self.width, self.height = self.image.size
        self._planes = None
        self._cache: dict = {}

    @property
    def planes(self):
        if self._planes is None:
            self._planes = _rgb_planes(self.image)
        return self._planes

    def _mask(self, name: str, build):
        got = self._cache.get(name)
        if got is None:
            got = self._cache[name] = build(*self.planes)
        return got

    @property
    def blue(self):
        return self._mask("blue", lambda r, g, b: (b >= 90) & ((b - r) >= 40) & ((b - g) >= 40) & (g <= 140))

    @property
    def white(self):
        return self._mask("white", lambda r, g, b: (r >= 250) & (g >= 250) & (b >= 250))

    @property
    def dark(self):
        import numpy as np

        return self._mask("dark", lambda r, g, b: np.maximum(np.maximum(r, g), b) <= 180)

    @property
    def ng_fill(self):
        return self._mask("ng_fill", lambda r, g, b: (b >= 140) & ((b - r) >= 80) & (b > g))

    @property
    def ng_track(self):
        return self._mask("ng_track", lambda r, g, b: (abs(r - g) <= 10) & (abs(g - b) <= 10) & (r >= 76) & (r <= 110))

    @property
    def ng_bg(self):
        return self._mask("ng_bg", lambda r, g, b: (r <= 80) & (g <= 80) & (b <= 80) & (abs(r - g) <= 12) & (abs(g - b) <= 12))


def _rgb_planes(image: Image.Image):
    """Кадр як три площини int16 — r, g, b.

    int16, а не uint8, свідомо: усі три ознаки нижче рахують РІЗНИЦІ каналів
    (`b - r >= 80`), а на uint8 віднімання переповнюється по колу й дає
    правдоподібне сміття замість відʼємного числа.
    """
    import numpy as np

    arr = np.asarray(image.convert("RGB"), dtype=np.int16)
    return arr[:, :, 0], arr[:, :, 1], arr[:, :, 2]


def find_newgen_progress(image: Image.Image, masks: "_FrameMasks | None" = None) -> Optional[ProgressBar]:
    """Смуга прогресу плаского UI нового покоління. None — якщо не впевнені."""
    import numpy as np

    m = masks or _FrameMasks(image)
    width, height = m.width, m.height
    fill_mask, track_mask, bg_mask = m.ng_fill, m.ng_track, m.ng_bg
    belongs_mask = fill_mask | track_mask

    def belongs(x: int, y: int) -> bool:
        return bool(belongs_mask[y, x])

    # Пробіги збираємо ВСІ, а не найдовший. Три уроки з бойових кадрів 150i
    # (04.09.26), кожен коштував ітерації:
    #  • між заливкою й треком стоїть ЗГЛАДЖЕНИЙ піксель (44,97,134) — не
    #    заливка й не трек. Він розривав пробіг, і детектор бачив лише праву,
    #    трекову половину смуги. Тому допуск NG_EDGE_SLACK усередині пробігу;
    #  • найдовший пробіг — НЕ наш: роздільник списку 819px (товщина 4) проти
    #    справжніх 555px. Перебираємо кандидатів, а не беремо перший;
    #  • один елемент дає пробіг на КОЖНОМУ своєму рядку, тож роздільник
    #    займав усі 40 слотів. Рахуємо РІЗНІ області (той самий урок, що з
    #    вікном G-коду на RemiCORE).
    #
    # Пробіг рахується від ПЕРШОГО до ОСТАННЬОГО свого пікселя включно, разом
    # із проковтнутими дірками (у попіксельній версії `run += gap + 1` давало
    # рівно `last - start + 1`). Розрив на дірці ширшій за NG_EDGE_SLACK: між
    # сусідніми належними пікселями тоді стоїть більше ніж slack порожніх,
    # тобто відстань між їхніми індексами більша за slack + 1.
    runs: list[tuple[int, int, int, int]] = []
    rows = range(height // 3, height, NG_ROW_STEP)
    for y in rows:
        idx = np.flatnonzero(belongs_mask[y])
        if idx.size == 0:
            continue
        breaks = np.flatnonzero(np.diff(idx) > NG_EDGE_SLACK + 1)
        starts = np.concatenate(([0], breaks + 1))
        ends = np.concatenate((breaks, [idx.size - 1]))
        for i, j in zip(starts, ends):
            start = int(idx[i])
            last = int(idx[j])
            run = last - start + 1
            if run >= NG_MIN_WIDTH:
                runs.append((run, start, last, y))
    runs.sort(key=lambda r: -r[0])

    seen: set[tuple[int, int]] = set()
    for length, x0, x1, y in runs:
        key = (x0 // 8, x1 // 8)
        if key in seen:
            continue
        seen.add(key)
        if len(seen) > MAX_BAR_CANDIDATES:
            break

        # Висота смуги — саме те, що відрізняє її від великих синіх кнопок.
        x_probe = (x0 + x1) // 2
        column = belongs_mask[:, x_probe]
        above = np.flatnonzero(~column[:y])
        top = int(above[-1]) + 1 if above.size else 0
        below = np.flatnonzero(~column[y + 1:])
        bottom = y + int(below[0]) if below.size else height - 1
        if not (NG_MIN_HEIGHT <= bottom - top + 1 <= NG_MAX_HEIGHT):
            continue

        # Смуга плаского UI лежить на ТЕМНІЙ картці (фон 66,66,66) — і саме цим
        # вона відрізняється від світло-сірого Windows-інтерфейсу RemiCORE, де
        # довгі сірі смуги трапляються скрізь (портретний .64 давав 12 хибних
        # спрацювань). Фон шукаємо в межах згладженого краю, а не рівно за
        # піксель: зліва від заливки 150i стоїть перехідний (44,97,134).
        y_probe = (top + bottom) // 2
        if x0 <= NG_EDGE_SLACK or x1 + NG_EDGE_SLACK + 1 >= width:
            continue
        left_bg = bool(bg_mask[y_probe, x0 - 1 - NG_EDGE_SLACK:x0].any())
        right_bg = bool(bg_mask[y_probe, x1 + 1:x1 + NG_EDGE_SLACK + 2].any())
        if not (left_bg and right_bg):
            continue

        # Заливка — суцільний ПРЕФІКС зліва.
        # Заливка — суцільний ПРЕФІКС зліва: довжина до першої не-заливки.
        prefix = fill_mask[y_probe, x0:x1 + 1]
        stop = np.flatnonzero(~prefix)
        fill = int(stop[0]) if stop.size else int(prefix.size)
        percent = round(fill * 100 / length)
        if percent < 0 or percent > 100:
            continue
        return ProgressBar(
            percent=percent, fill_width=fill, container_width=length,
            box=(x0, top, x1 + 1, bottom + 1),
        )
    return None




# ── Екран SUMMARY нового покоління: програма ЗАВЕРШЕНА ──────────────────────
# Коли CORiTEC доганяє програму, він показує підсумок: «SUMMARY», плитки
# Duration/Blanks/Jobs і рядок PROTOCOL зі станом «Completed». Смуги прогресу
# на цьому екрані НЕМАЄ ЗОВСІМ, тож усі три детектори вище чесно мовчать — і
# верстат виглядає так само, як зупинений («—»). Для цеху це різні речі:
# завершений верстат треба розвантажити.
#
# Розпізнаємо за ЗАГОЛОВКОМ, а не за зеленим кружком «Completed»: кружок малий
# і зелені елементи в цьому інтерфейсі є й на інших екранах (кнопка старту),
# а слово «SUMMARY» не трапляється більше ніде. Заголовок відцентрований —
# шукаємо його у вікні ±200px від середини кадру, у смузі 5-11% висоти (нижче
# статусного рядка з назвою моделі й годинником, вище плиток).
#
# Порівняння — маска світлих пікселів проти еталона, знятого з бойового кадру
# .81 (04.09.26, 1920×1200). Допуск 3%: на відміну від цифри, де хибний збіг
# дає ХИБНЕ ЧИСЛО і тому діє правило «піксель-у-піксель», тут ціна помилки
# менша (стан, а не число), а згладжування шрифту між машинами може дати
# кілька різних пікселів. 3% від 735 чорнильних пікселів — це ~22 пікселі,
# тобто менше за одну літеру: випадкове слово так не збігається.
SUMMARY_BAND = (0.05, 0.11)
SUMMARY_HALF_WIDTH = 200
SUMMARY_INK = 150
SUMMARY_MAX_MISMATCH = 0.03


