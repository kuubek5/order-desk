"""Що вважається листом у «Вхідних» CRM — ОДИН предикат (власник 30.09.26).

«Вхідні» дзеркалять Вхідні скриньки: новий лист, не відфільтрований правилом,
не перенесений у папку, не зниклий зі скриньки, не на паузі. І ще один випадок:
лист уже ПРИЙНЯТИЙ у CRM, але його повернули у Вхідні прямо в пошті
(`reopened_at`) — помилково перенесли, переробка, дописати файли. Такий лист
показується у «Вхідних» з позначкою, робота не чіпається.

Досі умова жила копіями в кожному місці, що рахує «Вхідні», — та сама пастка,
що зламала видачу 30.09.26 (CLAUDE.md §14): змінили одну копію, решта мовчки
жили за старим правилом. Вкладка, її лічильник, «непрочитані», лічильник у
рейці — усі беруть звідси.
"""

from __future__ import annotations

from sqlalchemy import and_, or_

from app.mail_hold import not_on_hold
from app.models import EmailMessage

# Прийнятий лист, повернутий у Вхідні прямо в пошті.
reopened = and_(EmailMessage.status == "прийнято", EmailMessage.reopened_at.is_not(None))

# Стан CRM, з яким лист належить «Вхідним» (без місця в скриньці): новий або
# повернутий прийнятий. Синк бере саме його, щоб помітити «покинув Вхідні».
inbox_state = or_(EmailMessage.status == "нове", reopened)

# Лист у вкладці «Вхідні».
in_inbox = and_(
    inbox_state,
    EmailMessage.filter_category.is_(None),
    EmailMessage.mailbox_folder.is_(None),
    EmailMessage.inbox_gone_at.is_(None),
    not_on_hold,
)


def mark_back_in_inbox(row: EmailMessage, now) -> None:
    """Лист повернувся у Вхідні скриньки прямо в пошті (власник 30.09.26).

    Прийнятий — позначити, щоб CRM показала його у «Вхідних»; робота не
    чіпається. Відхилений — знову «нове», як робить кнопка «↩ У Вхідні» в CRM
    (відхилення нічого не створювало, відкочувати нічого). Новий і так там."""
    if row.status == "прийнято":
        row.reopened_at = now
    elif row.status == "відхилено":
        row.status = "нове"
