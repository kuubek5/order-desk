"""Одна подія — один рядок у лозі, а не сто на хвилину.

Навіщо. Кілька сторожів у застосунку викликаються на КОЖЕН кадр або кожен
запит, а стан, про який вони попереджають, тримається годинами: тека
калібрувальних кадрів заповнилась, зона печі читається обрізано, ключ
шифрування не підходить. Попередження при цьому правильне й потрібне — але
написане 600 разів за годину воно топить решту лога, і саме там, де людина
потім шукатиме справжню причину (08.09.26: лог цехового ПК за вечір — це
майже суцільно три однакові рядки, а серед них губився єдиний важливий про
вкладку з пробілом).

Правило. Перший раз — пишемо. Далі — не частіше ніж раз на `every_seconds`,
і в тексті видно, скільки разів подія повторилась. Замовкати назовсім не
можна: стан, про який ніхто не нагадує, живе місяцями.

Ключ — рядок, який ІДЕНТИФІКУЄ подію, а не її текст: `"machines.calib_full:
192.168.1.27-8765"`. Один зіпсований верстат не має глушити попередження про
сусідній.

Стан у памʼяті процесу: рестарт означає «розкажи заново», і це правильно —
після рестарту людина знову дивиться в лог.
"""

from __future__ import annotations

import threading
from time import monotonic

_lock = threading.Lock()
# ключ → (коли писали востаннє, скільки разів пропущено відтоді)
_seen: dict[str, tuple[float, int]] = {}

DEFAULT_INTERVAL_SECONDS = 3600.0


def due(key: str, *, every_seconds: float = DEFAULT_INTERVAL_SECONDS) -> int | None:
    """Чи писати зараз про подію `key`.

    `None` — мовчати (нещодавно вже писали). Число — писати; воно каже,
    скільки разів подія сталась ПІСЛЯ попереднього запису (0 — перший раз).
    Це число варто вставити в текст: «(ще 217 разів відтоді)» відрізняє
    разовий збій від того, що триває безперервно.
    """
    now = monotonic()
    with _lock:
        last = _seen.get(key)
        if last is not None and now - last[0] < every_seconds:
            _seen[key] = (last[0], last[1] + 1)
            return None
        skipped = last[1] if last is not None else 0
        _seen[key] = (now, 0)
        return skipped


def clear(key: str) -> None:
    """Стан минув (тека звільнилась, значення перезаписали) — наступний раз
    буде новою подією, про яку скажемо одразу."""
    with _lock:
        _seen.pop(key, None)


def reset_for_tests() -> None:
    with _lock:
        _seen.clear()
